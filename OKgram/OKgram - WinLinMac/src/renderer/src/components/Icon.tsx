export type IconName = keyof typeof PATHS

export function Icon({ name, size = 18, filled = false }: { name: IconName; size?: number; filled?: boolean }) {
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? 'currentColor' : 'none'}
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: PATHS[name] }}
    />
  )
}

interface IconButtonProps extends ButtonHTMLAttributes<HTMLButtonElement> {
  icon: IconName
  label: string
  size?: number
  tone?: 'normal' | 'danger'
  filled?: boolean
  active?: boolean
}

export function IconButton({ icon, label, size = 18, tone = 'normal', filled, active, className = '', ...rest }: IconButtonProps) {
  return (
    <button
      type="button"
      className={`icon-button ${tone === 'danger' ? 'tone-danger' : ''} ${active ? 'active' : ''} ${className}`}
      title={label}
      aria-label={label}
      aria-pressed={active === undefined ? undefined : active}
      {...rest}
    >
      <Icon name={icon} size={size} filled={filled} />
    </button>
  )
}

